// Turns the four logo files the app draws (assets/brand/svg) into src/components/brandsvg.ts, so react-native-svg can render them with SvgXml on
// every platform without a Metro transformer. Gradient ids get a per-file prefix: on the web several inline SVGs share one id space.
// Run after changing a logo: node scripts/brand-svg.js
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const files = {
  symbolColor: '01_symbol_color.svg',
  symbolReversed: '04_symbol_reversed.svg',
  wordmarkDark: '05_wordmark_dark.svg',
  wordmarkWhite: '06_wordmark_white.svg',
};

const out = ['// Generated by scripts/brand-svg.js from assets/brand/svg. Do not edit by hand.', ''];
for (const [name, file] of Object.entries(files)) {
  let svg = fs.readFileSync(path.join(root, 'assets/brand/svg', file), 'utf8').replace(/\s+/g, ' ').trim()
    // attributes react-native-svg passes to the DOM as unknown props on the web; the label comes from the component instead
    .replace(/ objectBoundingBox="[^"]*"/g, '').replace(/ role="[^"]*"/g, '').replace(/ aria-label="[^"]*"/g, '');
  const ids = [...svg.matchAll(/id="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) {
    svg = svg.replaceAll(`id="${id}"`, `id="${name}-${id}"`).replaceAll(`url(#${id})`, `url(#${name}-${id})`);
  }
  out.push(`export const ${name} = ${JSON.stringify(svg)};`);
}
fs.writeFileSync(path.join(root, 'src/components/brandsvg.ts'), out.join('\n') + '\n');
console.log('wrote src/components/brandsvg.ts');
